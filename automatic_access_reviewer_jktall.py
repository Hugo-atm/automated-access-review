    result_df_eg2 = process_key_rack_mapping_eg2(input_file_path_eg2, output_csv_path_eg2)

    # Merge KeyTag mappings from EG1 and EG2
    merged_keytag_mapping = {}

    # Merge EG1 mappings
    for _, row in result_df_eg1.iterrows():
        group = row['KeyTag Group']
        keytags = row['KeyTags'].split(', ')

        if group not in merged_keytag_mapping:
            merged_keytag_mapping[group] = set()
        merged_keytag_mapping[group].update(keytags)

    # Merge EG2 mappings
    for _, row in result_df_eg2.iterrows():
        group = row['KeyTag Group']
        keytags = row['KeyTags'].split(', ')

        if group not in merged_keytag_mapping:
            merged_keytag_mapping[group] = set()
        merged_keytag_mapping[group].update(keytags)

    # Create merged DataFrame
    merged_rows = []
    for group, keytags in merged_keytag_mapping.items():
        merged_rows.append({
            "KeyTag Group": group,
            "KeyTags": ", ".join(sorted(keytags))
        })

    combined_keytag_df = pd.DataFrame(merged_rows)

    # Save merged mapping
    combined_keytag_output_path = r'/content/Key_Rack_Mapping_Combined.csv'
    combined_keytag_df.to_csv(combined_keytag_output_path, index=False)
    print(f"\nMerged KeyTag Mapping saved to: {combined_keytag_output_path}")

    # Create mapping of Cust groups to allowed KeyTags
    cust_group_to_keytags = {
        row["KeyTag Group"]: set(row["KeyTags"].split(", "))
        for _, row in combined_keytag_df.iterrows()
    }

    # Load user data
    user_data_file_path = r'/content/KMS_User_data_Final.csv'
    user_data_df = pd.read_csv(user_data_file_path)

    # Filter out Administration users and keep only User level users
    user_data_df = user_data_df[user_data_df['Terminal user level'] == 'User']

    # Validation results
    validation_results = []

    # Process each user
    for _, user in user_data_df.iterrows():
        # Extract user details
        user_name = f"{user['First Name']} {user['Last Name']}"

        # Split Cust groups and KeyTags
        cust_groups = str(user["Cust group"]).split(" ;")
        key_tags = set(str(user["Key tag"]).replace("keyTag ", "").split(" ;"))

        # Collect all valid KeyTags based on user's Cust groups
        valid_keytags = set()
        for group in cust_groups:
            valid_keytags.update(cust_group_to_keytags.get(group, set()))

        # Determine valid and invalid KeyTags
        valid_user_keytags = key_tags.intersection(valid_keytags)
        invalid_user_keytags = key_tags - valid_keytags

        # Record result
        validation_results.append({
            'User Name': user_name,
            'Terminal User Level': user['Terminal user level'],  # Added Terminal User Level
            'Cust Group': " ; ".join(cust_groups),
            'Valid KeyTags': ", ".join(valid_user_keytags) if valid_user_keytags else "None",
            'Invalid KeyTags': ", ".join(invalid_user_keytags) if invalid_user_keytags else "None"
        })

    # Create DataFrame from validation results
    validation_df = pd.DataFrame(validation_results)

    # Save validation results
    validation_output_path = r'/content/KMS_validation_result.csv'
    validation_df.to_csv(validation_output_path, index=False)
    print(f"\nKeyTag Access Validation results saved to: {validation_output_path}")

    # Optional: Print results to console
    print("\nValidation Results Preview:")
    print(validation_df)

