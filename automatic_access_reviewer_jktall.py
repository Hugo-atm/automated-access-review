def get_keytag_eg1(row, sub_row, col):
    if sub_row == 1:
        return f"C{row:02d}{col:02d}"
    elif sub_row == 2:
        adjusted_col = col + 16
        return f"C{row:02d}{adjusted_col:02d}"
