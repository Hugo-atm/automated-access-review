def extract_user_info(user_info_str):
    """Extract user information from the formatted string."""
    # Check if input is valid
    if pd.isna(user_info_str) or not isinstance(user_info_str, str):
        print(f"Invalid user info input: {user_info_str}")
        return {
            'First Name': '',
            'Last Name': '',
            'E-mail address': '',
            'Mobile phone number': '',
            'Department': '',
            'Terminal user level': '',
            'User Groups': ''
        }

    # Initialize dictionary with empty values
    info = {
        'First Name': '',
        'Last Name': '',
        'E-mail address': '',
        'Mobile phone number': '',
        'Department': '',
        'Terminal user level': '',
        'User Groups': ''
    }

    try:
        # Define patterns to extract information
        patterns = {
            'First Name': r'First name:\s*(.*?)(?=Last name:|$)',
            'Last Name': r'Last name:\s*(.*?)(?=E-mail address:|$)',
            'E-mail address': r'E-mail address:\s*(.*?)(?=Mobile phone number:|$)',
            'Mobile phone number': r'Mobile phone number:\s*(.*?)(?=Landline number:|$)',
            'Department': r'Department:\s*(.*?)(?=Terminal user level:|$)',
            'Terminal user level': r'Terminal user level:\s*(.*?)(?=Max|$)'
        }

        # Extract each field using regex
        for field, pattern in patterns.items():
            match = re.search(pattern, user_info_str, re.DOTALL)
            if match:
                info[field] = match.group(1).strip()

        # Extract user groups from user group section
        user_groups_pattern = r'user group:\s*(.*?)(?=Valid:|$)'
        user_groups_match = re.search(user_groups_pattern, user_info_str, re.DOTALL)
        if user_groups_match:
            groups_text = user_groups_match.group(1)
            # Extract group names (Admin or full Cust-XXX patterns)
            group_names = re.findall(r'\d+=(Admin|Cust-\d+(?:-[A-Z]+)?)', groups_text)
            # Join the group names with semicolons
            info['User Groups'] = ' ;'.join(group_names) if group_names else ''

        return info

    except Exception as e:
        print(f"Error extracting user info: {e}")
        print(f"From string: {user_info_str}")
        return info

def extract_credentials(credentials_str):
    """Extract RFID from credentials string."""
    if pd.isna(credentials_str) or not isinstance(credentials_str, str):
        return {'RFID': ''}

    try:
        # Extract RFID (number after comma)
        rfid_match = re.search(r',\s*(\d+)', credentials_str)
        rfid = rfid_match.group(1) if rfid_match else ''

        return {
            'RFID': rfid
        }
    except Exception as e:
        print(f"Error processing credentials: {e}")
        return {'RFID': ''}

def process_csv(KMS_User_data_raw_extraction, output_file_path):
    """Process the input CSV file and create a new formatted CSV."""
    try:
        # Read the input CSV file
        data = pd.read_csv(KMS_User_data_raw_extraction)

        # Print column names for debugging
        print("Available columns in CSV:", data.columns.tolist())

        # Skip the header row and process from the second row
        data_processed = data.iloc[1:].copy()

        # Initialize list to store processed records
        processed_records = []

        # Process each row
        for index, row in data_processed.iterrows():
            try:
                # Skip rows that contain administrative information
                if 'Administrator' in str(row['0']):
                    continue

                # Extract information using the correct column indices
                user_info = extract_user_info(str(row['1']))
                cred_info = extract_credentials(str(row['2']))
                key_tag = str(row['3']) if not pd.isna(row['3']) else ''
                cust_group = str(row['4']) if not pd.isna(row['4']) else ''

                # Remove leading/trailing semicolons and spaces from key_tag and cust_group
                key_tag = key_tag.strip('; ')
                cust_group = cust_group.strip('; ')

                # Combine all information
                record = {
                    **user_info,
                    **cred_info,
                    'Key tag': key_tag,
                    'Cust group': cust_group
                }

                processed_records.append(record)

            except Exception as e:
                print(f"Error processing row {index}:")
                print(f"Row data: {row}")
                print(f"Error details: {e}")
                continue

        # Create DataFrame with processed records
        columns = [
            'First Name', 'Last Name', 'E-mail address', 'Mobile phone number',
            'Department', 'Terminal user level', 'User Groups', 'RFID',
            'Key tag', 'Cust group'
        ]

        output_df = pd.DataFrame(processed_records, columns=columns)

        # Print summary
        print(f"\nProcessed {len(processed_records)} records")
        print("\nFirst few rows of processed data:")
        print(output_df.head())

        # Save to CSV
        output_df.to_csv(output_file_path, index=False)
        print(f"\nProcessed data saved to {output_file_path}")
        return output_df

    except Exception as e:
        print(f"Error processing CSV file: {e}")
        return pd.DataFrame()

