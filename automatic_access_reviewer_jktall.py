def map_keytags_to_groups_eg1(df_eg1):
    keytag_mapping_eg1 = {}
    current_row_eg1 = None

    for idx, row in df_eg1.iterrows():
        if pd.isna(row['Final']):
            continue

        physical_row_eg1 = row['Final']

        if current_row_eg1 != physical_row_eg1:
            current_row_eg1 = physical_row_eg1
            sub_row_eg1 = 1
        else:
            sub_row_eg1 = 2

        for col in range(1, 17):
            col_label = f"{col:02d}"
            keytag_group_eg1 = row[col_label]

            if pd.notna(keytag_group_eg1):
                keytag_eg1 = get_keytag_eg1(int(physical_row_eg1), sub_row_eg1, col)

                if keytag_group_eg1 not in keytag_mapping_eg1:
                    keytag_mapping_eg1[keytag_group_eg1] = []
                if keytag_eg1 and keytag_eg1 not in keytag_mapping_eg1[keytag_group_eg1]:
                    keytag_mapping_eg1[keytag_group_eg1].append(keytag_eg1)

    return keytag_mapping_eg1

